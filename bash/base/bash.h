int Exec(struct Tokenizer *t) {


    if (t->token_count==0) {
        return 0;
    }


    int pid = -1;

    while (true) {
        pid = fork();
        if (pid < 0) {
            return -1;
            continue;
        }
        if (pid>0) {
            break;
        }
        //pid == 0

        char* arr[t->token_count+1];
        struct Token* nxt = t->head;
        for (int i = 0; i < t->token_count; i++) {
            arr[i] = nxt->start;
            for (int j = 0;; j++) {
                if (arr[i][j]=='\n' || arr[i][j]=='\0' || arr[i][j]==' ') {
                    arr[i][j] = '\0';
                    break;
                }
            }
            nxt = nxt->next;
            //printf("id %d = %s \n", i, arr[i]);
        }
        arr[t->token_count] = NULL;
        execvp(t->head->start, arr);

        printf("Command not found");
        return -1;
        //exit(-1000);
    }


    int status = 0;
    waitpid(pid, &status, 0);



    return 0;







}










